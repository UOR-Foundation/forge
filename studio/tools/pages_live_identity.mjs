// Project-owned deployment observation boundary. The manifest addresses actual assembled bytes,
// not the run that happened to observe a mutable production URL.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const marker = 'pages-deployment.json';
export function createManifest(root) {
 const files = {};
 function walk(dir, prefix = '') {
  for (const entry of fs.readdirSync(dir, {withFileTypes:true}).sort((a,b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
   const rel = prefix + entry.name;
   if (rel === marker) continue;
   if (entry.isDirectory()) walk(path.join(dir, entry.name), rel + '/');
   else if (entry.isFile()) files[rel] = hash(fs.readFileSync(path.join(dir, entry.name)));
   else throw new Error('pagesLiveIdentityMismatch: non-regular artifact file');
  }
 }
 walk(root);
 if (!files['index.html']) throw new Error('pagesLiveIdentityMismatch: missing index');
 return {schema:1, digest:hash(JSON.stringify(files)), files};
}
export async function assertDeployment(base, expected, fetcher = fetch) {
 const url = new URL(marker, base);
 url.searchParams.set('observation', `${Date.now()}-${Math.random()}`);
 const response = await fetcher(url, {cache:'no-store', redirect:'error', signal:AbortSignal.timeout(30000)})
  .catch(error => { throw new Error(`pagesLiveIdentityMismatch: ${error.message}`); });
 const actual = response.ok ? await response.json() : null;
 if (!actual || ['schema','digest','source','run','attempt'].some(key => actual[key] !== expected[key]))
  throw new Error('pagesLiveIdentityMismatch: deployment was superseded, changed or not observed');
}
export async function assertArtifact(base, manifest, fetcher = fetch) {
 if (!manifest || manifest.schema !== 1 || !manifest.files || !manifest.files['index.html'] || hash(JSON.stringify(manifest.files)) !== manifest.digest)
  throw new Error('pagesLiveIdentityMismatch: malformed artifact manifest');
 const entries = Object.entries(manifest.files);
 let next = 0;
 await Promise.all(Array.from({length:Math.min(12, entries.length)}, async () => {
  while (next < entries.length) {
   const [file, digest] = entries[next++];
   const url = new URL(file.split('/').map(encodeURIComponent).join('/'), base);
   url.searchParams.set('observation', `${Date.now()}-${Math.random()}`);
   const response = await fetcher(url, {cache:'no-store', redirect:'error', signal:AbortSignal.timeout(30000)})
    .catch(error => { throw new Error(`pagesLiveResponseMismatch: ${error.message}`); });
   if (!response.ok || hash(Buffer.from(await response.arrayBuffer())) !== digest)
    throw new Error(`pagesLiveResponseMismatch: ${file}`);
  }
 }));
}
function relative(base, url) {
 const root = new URL(base), target = new URL(url);
 if (root.origin !== target.origin || !target.pathname.startsWith(root.pathname)) return null;
 const rel = decodeURIComponent(target.pathname.slice(root.pathname.length));
 return rel.endsWith('/') || rel === '' ? rel + 'index.html' : rel;
}
function staticPath(manifest, base, url, navigation = false) {
 const rel = relative(base, url);
 if (rel === null) return null;
 if (navigation && rel.startsWith('ui/')) return 'ui/index.html';
 if (Object.hasOwn(manifest.files, rel)) return rel;
 // Match the worker's renderer fallback ownership; p/ and holo/ remain generated previews.
 const separate = /^(?:app|ui|p|holo|v1|engine|assets|scaffold|editor|compiler|live|q|kernel|prism|prism-code|fonts|wallpapers)(?:\/|$)/.test(rel);
 return navigation && !separate ? 'index.html' : rel;
}
export function responseIdentity(manifest, base, url, body, navigation = false) {
 const rel = staticPath(manifest, base, url, navigation);
 // Preview documents are generated by the verified service worker, not deployed artifact files.
 if (!Object.hasOwn(manifest.files, rel)) return false;
 if (hash(body) !== manifest.files[rel]) throw new Error(`pagesLiveResponseMismatch: ${rel}`);
 return true;
}
export function observeResponses(context, manifest, base) {
 const pending = new Set(), requests = new Set(), failures = [];
 context.on('request', request => { if (Object.hasOwn(manifest.files, staticPath(manifest, base, request.url(), request.isNavigationRequest?.()))) requests.add(request); });
 context.on('requestfinished', request => requests.delete(request));
 context.on('requestfailed', request => {
  if (Object.hasOwn(manifest.files, staticPath(manifest, base, request.url(), request.isNavigationRequest?.()))) failures.push(new Error(`pagesLiveResponseMismatch: request failed: ${request.url()}`));
  requests.delete(request);
 });
 let index = false;
 context.on('response', response => {
  const navigation = response.request?.().isNavigationRequest?.();
  const rel = staticPath(manifest, base, response.url(), navigation);
  if (!Object.hasOwn(manifest.files, rel)) return;
  const task = Promise.resolve().then(async () => {
   responseIdentity(manifest, base, response.url(), await response.body(), navigation);
   if (rel === 'index.html') index = true;
  }).catch(error => failures.push(new Error(`pagesLiveResponseMismatch: ${error.message}`))).finally(() => pending.delete(task));
  pending.add(task);
 });
 return async () => {
  while (pending.size) await Promise.all([...pending]);
  if (failures.length) throw failures[0];
  if (requests.size) throw new Error('pagesLiveResponseMismatch: unfinished static requests');
  if (!index) throw new Error('pagesLiveResponseMismatch: no verified index observed');
 };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
 const [command, target, file] = process.argv.slice(2);
 if (command === 'create') {
  const manifest = createManifest(target);
  const identity = {schema:1, digest:manifest.digest, source:process.env.GITHUB_SHA, run:process.env.GITHUB_RUN_ID, attempt:process.env.GITHUB_RUN_ATTEMPT};
  if (!/^[a-f0-9]{40}$/.test(identity.source) || !/^\d+$/.test(identity.run) || !/^\d+$/.test(identity.attempt)) throw new Error('pagesLiveIdentityMismatch: missing run identity');
  fs.writeFileSync(file, JSON.stringify(manifest));
  fs.writeFileSync(path.join(target, marker), JSON.stringify(identity));
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, `digest=${manifest.digest}\n`);
 } else if (command === 'check') await assertDeployment(target, JSON.parse(fs.readFileSync(file,'utf8')));
 else if (command === 'artifact') await assertArtifact(target, JSON.parse(fs.readFileSync(file,'utf8')));
 else throw new Error('pagesLiveIdentityMismatch: expected create or check');
}
